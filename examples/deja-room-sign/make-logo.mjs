// 🚂 Regenerate logo.h — the DEJA.js mark as a 24x24 RGB565 bitmap for the sign's header.
//   node make-logo.mjs /path/to/DEJA.js/apps/dejajs-www/public/icon-512.png
// Needs `sharp`: run it from a directory where sharp resolves (the DEJA.js checkout has it),
// e.g.  cd DEJA.js && node ../model-railroad-arduino-animation-lib/examples/deja-room-sign/make-logo.mjs apps/dejajs-www/public/icon-512.png
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const sharp = createRequire(join(process.cwd(), 'package.json'))('sharp')
const BG = { r: 14, g: 16, b: 20 }   // the sign's ground = the site's #0E1014 (C_BG 0x0882)
const SIZE = 24
const src = process.argv[2]
if (!src) { console.error('usage: node make-logo.mjs <icon.png>'); process.exit(1) }

const { data, info } = await sharp(src).resize(SIZE, SIZE, { fit: 'contain', background: { ...BG, alpha: 0 } }).raw().toBuffer({ resolveWithObject: true })
const words = []
for (let i = 0; i < info.width * info.height; i++) {
  const r = data[i * 4], g = data[i * 4 + 1], b = data[i * 4 + 2], a = data[i * 4 + 3] / 255
  const R = Math.round(a * r + (1 - a) * BG.r), G = Math.round(a * g + (1 - a) * BG.g), B = Math.round(a * b + (1 - a) * BG.b)
  words.push(((R & 0xF8) << 8) | ((G & 0xFC) << 3) | (B >> 3))
}
let out = `// 🚂 The DEJA.js mark (apps/dejajs-www/public/icon-512.png) as a ${SIZE}x${SIZE} RGB565 bitmap,\n`
out += "// pre-composited on the sign's ground (#0E1014). Generated by make-logo.mjs — regenerate rather than edit.\n#pragma once\n#include <stdint.h>\n"
out += `const int16_t LOGO_W = ${SIZE}, LOGO_H = ${SIZE};\nconst uint16_t LOGO[${SIZE * SIZE}] PROGMEM = {\n`
for (let y = 0; y < SIZE; y++) out += '  ' + words.slice(y * SIZE, (y + 1) * SIZE).map((w) => '0x' + w.toString(16).toUpperCase().padStart(4, '0')).join(',') + ',\n'
out += '};\n'
const dest = join(dirname(fileURLToPath(import.meta.url)), 'logo.h')
writeFileSync(dest, out)
console.log(`wrote ${dest} (${SIZE}x${SIZE})`)
