#!/usr/bin/env node
// 🧬 Reads every effect header in src/ and writes web/js/schema.js: each
// class's constructor pins and Config fields (type, default, help text), plus
// the enums they use. The web configurator and the firmware generator both
// read this, so the headers stay the single source of truth.
//
//   node tools/gen-schema.mjs           write web/js/schema.js
//   node tools/gen-schema.mjs --check   fail if it's out of date (CI)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SIZES = { uint8_t: 1, int8_t: 1, bool: 1, uint16_t: 2, int16_t: 2, int: 2, uint32_t: 4, int32_t: 4, float: 4 }
const NO_PIN = 255

export function parseHeaders(srcDir) {
  const files = readdirSync(srcDir).filter((f) => /^MRA_.*\.h$/.test(f)).sort()
  const enums = {}
  const sources = files.map((f) => [f, readFileSync(join(srcDir, f), 'utf8')])

  // public enums at namespace level: enum Name : uint8_t { A, B, C };
  for (const [, src] of sources) {
    for (const m of src.matchAll(/^enum (\w+) : uint8_t \{([^}]*)\};/gm)) {
      enums[m[1]] = m[2].split(',').map((s) => s.trim()).filter(Boolean)
    }
  }

  const value = (raw, type) => {
    raw = raw.trim()
    if (raw === 'NO_PIN') return NO_PIN
    if (raw === 'true' || raw === 'false') return raw === 'true'
    if (enums[type]) {
      const i = enums[type].indexOf(raw)
      if (i < 0) throw new Error(`unknown ${type} value ${raw}`)
      return raw
    }
    const n = Number(raw.replace(/f$/, ''))
    if (Number.isNaN(n)) throw new Error(`can't read default "${raw}"`)
    return n
  }

  const classes = {}
  for (const [file, src] of sources) {
    for (const cm of src.matchAll(/^class (\w+) \{([\s\S]*?)^\};/gm)) {
      const [, name, body] = cm
      const cfg = body.match(/struct Config \{([\s\S]*?)\} cfg;/)
      if (!cfg) continue

      // 🎛️ Config fields, with trailing (and continued) comments as help
      const fields = []
      let last = []
      for (const line of cfg[1].split('\n')) {
        const comment = (line.match(/\/\/\s?(.*)$/) || [])[1]
        const code = line.replace(/\/\/.*$/, '').trim()
        if (!code) {
          if (comment && last.length) for (const f of last) f.help += ' ' + comment.trim()
          continue
        }
        const dm = code.match(/^(\w+)\s+(.+);$/)
        if (!dm) throw new Error(`${file}: can't parse "${code}"`)
        const type = dm[1]
        if (!SIZES[type] && !enums[type]) throw new Error(`${file}: unknown type ${type}`)
        last = dm[2].split(',').map((d) => {
          const [fname, raw] = d.split('=').map((s) => s.trim())
          const f = { name: fname, type, default: value(raw, type), help: (comment || '').trim() }
          fields.push(f)
          return f
        })
      }
      for (const f of fields) f.help = f.help.replace(/\s+/g, ' ').replace(/^…|…$/g, '').trim()

      // 📌 constructor pins: uint8_t params with defaults
      const ctor = src.match(new RegExp(`\\b${name}\\(([^)]*)\\)\\s*:`))
      const pins = []
      for (const p of ctor[1].split(',')) {
        const pm = p.trim().match(/^uint8_t (\w+) = (\w+)$/)
        if (pm) pins.push({ name: pm[1], default: value(pm[2], 'uint8_t') })
      }
      classes[name] = { header: file, pins, fields }
    }
  }
  return { sizes: SIZES, enums, classes }
}

export function render(schema) {
  return `// 🧬 Generated by tools/gen-schema.mjs from src/*.h. Don't edit: change the
// headers and run \`node tools/gen-schema.mjs\`.
export default ${JSON.stringify(schema, null, 2)}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = join(root, 'web/js/schema.js')
  const text = render(parseHeaders(join(root, 'src')))
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(out, 'utf8') } catch {}
    if (current !== text) { console.error('❌ web/js/schema.js is out of date: run node tools/gen-schema.mjs'); process.exit(1) }
    console.log('✅ web/js/schema.js is up to date')
  } else {
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
  }
}
